"""動画のサムネイルに載せる文言と、図解イラストの材料を生成する。

サムネイル画像に大きく表示できる文字数はごく少ない(1〜2行、20文字程度まで)
ため、他のエージェントのような生成→評価→修正のループは行わず、
1回の生成呼び出しのみで済ませる軽量な設計にしている。

main_text/sub_textだけをGeminiに渡すと、単に「文字+汎用的な背景」の
サムネイルにしかならない(実際にそうなった)。良いサムネイルは、比較構造や
具体的な数値をアイコン・パネルなどの図解で見せている場合が多いため、
visual_summaryとして動画の核心的な内容を要約し、Geminiが自律的に
図解をデザインするための材料として渡す。
"""

from video_pipeline.claude_client import call_json
from video_pipeline.config import MODEL_GENERATE

LABEL = "サムネイルエージェント"

GENERATE_SYSTEM = """あなたはYouTubeサムネイルの企画担当です。
動画台本をもとに、サムネイルに使う文言と、Gemini画像生成モデルが図解イラストを
デザインするための材料を作成してください。

出力する3項目:
- main_text: サムネイルに大きく載せる最重要キーワード。文章ではなく
  体言止めの短いキーワード1つに絞る(6〜10文字程度)。サムネイルは
  小さいサイズで一瞬しか見られないため、文で説明しようとせず、
  一目で意味が伝わる語に凝縮する（良い例:「95%が失敗」「AI現場力」
  「精度83%」。避けるべき例:「汎用AIだけじゃダメ？」のような
  一文丸ごとの説明的なコピー）。数値を載せる場合は、単独で見たときに
  誰・何についての数値かを読み違えられないよう、必要なら主語や
  ごく短い修飾語を含める（悪い例：記事の主張が「人間の検知率は低く、
  AIの検知率は高い」なのに、主語を省いて「検知率わずか5%」とすると
  AI側の数値であるかのように読め、記事の主張と正反対の印象を
  与えてしまう。良い例:「人間の検知率5%」）。また、同じ対象について
  条件によって異なる複数の数値が台本に出てくる場合（例:「平均13.6%、
  慣れると5%まで低下」）は、条件を省いた特定条件下の数値だけを
  切り取らない。動画の主張を代表する数値（上記の例なら平均値13.6%）を
  優先して選ぶか、条件語を含めて誤解のない形にする（悪い例:平均が
  13.6%なのに「人間検知率5%」とだけ書くと、常に5%であるかのように
  誤読される）
- sub_text: main_textを補強する2つ目の短いキーワード(体言止め、
  6〜10文字程度)。文字要素が多いサムネイルほどスマホ画面では読まれず
  クリック率が下がる傾向が実際のデータで確認されているため、基本は
  空文字にしてmain_textの数字・キーワード1つだけに情報を絞ることを
  優先する。main_text単体だと対象や単位が曖昧で誤読されうる場合など、
  補強がどうしても必要なときに限り短く追加してよい
- visual_summary: この動画の核心的な内容を2〜3文で要約したもの。
  Geminiがこれを読んで比較図・アイコン・矢印などの図解イラストを
  自律的にデザインするための材料になるので、以下を必ず含める:
  - 対比構造があれば両方の対象を明示する（例:「汎用AIは借り物のモデルで
    差別化しにくい。一方、自前モデルは模倣されにくい資産になる」）
  - 具体的な数値・キーワードがあれば含める（例:「精度は0.79から0.83に改善」）
  - 単なる感想ではなく、図解の材料になる具体的な内容にする

制約:
- 誇張・釣りタイトルにはしない(台本の内容と矛盾しない範囲にする)
- 台本冒頭0:00〜1:00の概要パートの内容を踏まえる

出力はJSONのみ: {"main_text": "...", "sub_text": "...", "visual_summary": "..."}
"""


def generate(script: str, video_title: str | None = None) -> dict:
    """台本からサムネイル用の文言と図解材料(visual_summary)を生成する。

    video_title: 指定すると、その動画のYouTubeタイトルと矛盾しない・
    むしろ補強し合う文言になるよう指示する(未指定の場合は台本のみから生成)。
    """
    user = f"# 動画台本\n\n{script}\n\n"
    if video_title:
        user += (
            f"# この動画のYouTubeタイトル\n\n{video_title}\n\n"
            "上記のタイトルと矛盾しない文言にしてください。タイトルの丸写しでは"
            "なく、タイトルだけでは伝えきれていない驚きの数字やキーワードを"
            "補強する形が望ましいです。\n\n"
        )
    user += "上記からサムネイル用の文言と図解材料(visual_summary)を作成してください。"
    result = call_json(GENERATE_SYSTEM, user, model=MODEL_GENERATE)
    return {
        "main_text": result.get("main_text", ""),
        "sub_text": result.get("sub_text", ""),
        "visual_summary": result.get("visual_summary", ""),
    }

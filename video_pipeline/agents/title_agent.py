"""動画のYouTubeタイトルを生成する。

記事の見出し1をそのまま使うと、網羅的だが視聴者の「自分に関係がある」を
刺激しないタイトルになりがち（実際のチャンネル分析で長尺動画のクリック率が
1%を下回る一因として指摘された）。台本の内容をもとに、視聴者の課題・不安に
直接語りかける短いフックの効いたタイトルを作る。サムネイル・ショートの
フック文言と同じく、1回の生成呼び出しのみで済ませる軽量な設計にしている。
"""

from video_pipeline.claude_client import call_text
from video_pipeline.config import MODEL_GENERATE

LABEL = "タイトルエージェント"

GENERATE_SYSTEM = """あなたはYouTube動画のタイトルを考えるコピーライターです。
動画台本をもとに、視聴者のクリック率(CTR)を最大化するYouTubeタイトルを
1つ作成してください。

タイトルの方針:
- 視聴者が「自分に関係がある」と感じる短いフレーズにする（例:「なぜあなたの
  AI開発は失敗するのか？」のように、読み手の課題・不安・好奇心に直接語りかける。
  「〜について解説します」のような説明的・平坦な言い回しにしない）
- 台本冒頭0:00〜1:00の概要パートで提示している具体的なメリット・驚きの数値を
  タイトルの軸にする(概要パートと矛盾しないこと)
- 全体で40文字前後に収める(長すぎるとYouTube検索結果や関連動画表示で
  途中で切れてしまう)
- 誇張・釣りタイトルにはしない(台本の内容と矛盾しない範囲にする)
- 短縮のために数値の主語を省略しない。「誰の/何についての数値か」が
  抜けると意味が逆転して読める場合がある(悪い例:台本が「人間の検知率
  13.6%→5%に対し、AIは89%」と対比しているのに、主語を省いて
  「検知率13.6%→5%の罠」とすると、AI側の数値が悪化しているかの
  ように読め、台本の主張と正反対の印象を与えてしまう。このような
  数値は「人間の」のような短い主語を残す)
- 【重要】クリックを誘うフックだけでなく、YouTube検索で見つけてもらう
  ためのキーワードも最低1つはタイトルに含める。動画の主題を表す固有名詞・
  技術用語（例: 企業名・製品名・技術/手法名・「RAG」「ファインチューニング」
  「画像生成AI」のような視聴者が実際に検索窓に打ち込みそうな語）を、
  抽象的な言い換え（例:「データ革命」「〇〇の正体」）だけで済ませずに
  そのまま残す。フック調の言い回しとキーワードは両立させること
  （悪い例:「4.4億枚のデータ革命、あなたのRAG設計は『タスク別』で
  止まってないか？」→ 画像生成AIやAlibabaの論文が主題だと分かる語が
  無く検索に引っかかりにくい。改善例:「Alibabaの画像生成AI論文が示す、
  タスク別データ設計が失敗する理由」のように主題キーワードを残しつつ
  フックも効かせる）

出力はタイトル文字列のみ。前置き・説明文・引用符・末尾の句点は不要です。
"""


def generate(script: str) -> str:
    """台本からYouTubeタイトルを生成する。"""
    user = f"# 動画台本\n\n{script}\n\n上記からYouTubeタイトルを1つ作成してください。"
    title = call_text(GENERATE_SYSTEM, user, model=MODEL_GENERATE)
    return title.strip().strip("「」\"'")

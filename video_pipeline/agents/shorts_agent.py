"""YouTubeショートの上下に載せる、強いフック文言を生成する。

サムネイル用のキャッチコピー(thumbnail_agent)をそのまま使うと、
ショートに必要な「一瞬でスクロールされずに止めてもらう」ための
インパクトが不足しがちだった(実際にそう指摘された)。ショートは横型動画・
サムネイルよりもさらに短い判断時間で見るかどうかが決まるため、専用の
より強いフック文言を考える軽量エージェントとして分離している
(他のエージェントと違い評価・修正ループは行わない単発の生成呼び出し)。
"""

from video_pipeline.claude_client import call_json
from video_pipeline.config import MODEL_GENERATE

LABEL = "ショートエージェント"

GENERATE_SYSTEM = """あなたはYouTubeショートのフック文言を考えるコピーライターです。
動画台本をもとに、ショート動画の上下に大きく載せる、強いフック文言を作成してください。

ショートはフィード上を高速でスクロールされる中で、一瞬で「見る/飛ばす」が
決まります。サムネイルよりもさらに強いインパクト・緊急性・curiosity gap
(続きが気になる引き)が必要です。

出力する2項目:
- hook_text: 上段に大きく載せる、1行8〜14文字程度の強いフック。
  具体的な驚きの数字、断定を避けた疑問形、「え」「まさか」「知らないと損」
  のような強い言葉を使う。「〜について解説します」のような丁寧・説明的な
  言い回しは絶対に避ける
  （良い例:「精度が4%も上がった」「9割の人が知らない」
   避けるべき例:「機械学習について解説する動画です」）
- follow_text: 下段に載せる、8〜16文字程度の補足。hook_textの続きが
  気になるように書く（例:「その理由が判明」「衝撃の理由とは」）

制約:
- 誇張・釣りタイトルにはしない(台本の内容と矛盾しない範囲にする)
- 台本冒頭0:00〜1:00の概要パートの内容を踏まえる
- 「です」「ます」で終わる説明的な文にしない(体言止めや短い断定で終わる)

出力はJSONのみ: {"hook_text": "...", "follow_text": "..."}
"""


def generate(script: str) -> dict:
    """台本からショート用のフック文言(hook_text/follow_text)を生成する。"""
    user = (
        f"# 動画台本\n\n{script}\n\n上記からショート用のフック文言を作成してください。"
    )
    result = call_json(GENERATE_SYSTEM, user, model=MODEL_GENERATE)
    return {
        "hook_text": result.get("hook_text", ""),
        "follow_text": result.get("follow_text", ""),
    }
